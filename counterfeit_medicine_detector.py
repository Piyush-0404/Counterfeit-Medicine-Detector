# 10. IMPROVED OCR -- PROXIMITY-BASED FIELD EXTRACTION
#     (bounding-box distance + fuzzy keyword matching, instead
#     of regex on one flattened string)
# ============================================================
import cv2
import easyocr
from rapidfuzz import fuzz

reader = easyocr.Reader(["en"], gpu=torch.cuda.is_available())

BATCH_KW = ["batch", "batch no", "b no", "b.no", "lot", "lot no"]
MFG_KW   = ["mfg", "mfd", "manufactured", "manufacturing date", "mfg date"]
EXP_KW   = ["exp", "expiry", "expires", "use before", "exp date"]
PRODUCT_KW = ["tablet", "tablets", "capsule", "capsules", "syrup",
              "injection", "mg", "ml", "ip", "usp"]

# [FIX-2] fuzz.partial_ratio against very short keywords (<=3 chars, e.g.
# "mg", "ml", "ip", "usp") matches almost any noisy OCR token, since a
# 2-3 char substring nearly always scores high against longer text.
# For short keywords we require a word-boundary regex match instead of
# fuzzy scoring; fuzzy matching is reserved for longer keywords where
# it's actually catching OCR typos rather than firing on noise.
SHORT_KEYWORD_LEN = 4  # keywords with fewer chars use exact/word-boundary matching


def _short_keyword_hit(text, keyword):
    return re.search(rf"(?<![a-z0-9]){re.escape(keyword)}(?![a-z0-9])", text.lower()) is not None


def preprocess_upscaled(image_bgr):
    return cv2.resize(image_bgr, None, fx=3, fy=3, interpolation=cv2.INTER_CUBIC)


def preprocess_clahe(image_bgr):
    upscaled = preprocess_upscaled(image_bgr)
    gray = cv2.cvtColor(upscaled, cv2.COLOR_BGR2GRAY)
    clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8, 8))
    return clahe.apply(gray)


def box_center(bbox):
    xs = [p[0] for p in bbox]
    ys = [p[1] for p in bbox]
    return float(np.mean(xs)), float(np.mean(ys))


def fuzzy_contains(text, keywords, threshold=75):
    """[FIX-2] Short keywords (len < SHORT_KEYWORD_LEN) use exact
    word-boundary matching; longer keywords still use fuzzy partial_ratio
    to tolerate OCR typos."""
    t = text.lower()
    for kw in keywords:
        if len(kw) < SHORT_KEYWORD_LEN:
            if _short_keyword_hit(t, kw):
                return True
        else:
            if fuzz.partial_ratio(kw, t) >= threshold:
                return True
    return False


DATE_PATTERN = r"(?:JAN|FEB|MAR|APR|MAY|JUN|JUL|AUG|SEP|OCT|NOV|DEC)[A-Z]*\s*[./-]?\s*\d{2,4}|\d{1,2}[./-]\d{1,2}[./-]\d{2,4}|\d{1,2}[./-]\d{4}|\d{4}[./-]\d{1,2}"


def clean_ocr_text(text):
    """Clean OCR text while preserving useful characters."""
    text = text.strip()
    text = re.sub(r"\s+", " ", text)
    return text


def extract_batch_number(ocr_results):
    """Extract a batch/lot number from an explicit batch label."""
    patterns = [
        r"(?:b\s*\.?\s*no|batch(?:\s*no)?|lot(?:\s*no)?)\s*[:.\-]?\s*([A-Z0-9][A-Z0-9./\-]{2,20})"
    ]

    for _, text, _ in ocr_results:
        text = clean_ocr_text(text)
        for pattern in patterns:
            match = re.search(pattern, text, re.IGNORECASE)
            if match:
                value = match.group(1).strip(" .:-")
                if not re.search(r"(?:MFG|EXP|JAN|FEB|MAR|APR|MAY|JUN|JUL|AUG|SEP|OCT|NOV|DEC)", value, re.I):
                    return value

    full_text = " ".join(clean_ocr_text(text) for _, text, _ in ocr_results)
    for pattern in patterns:
        match = re.search(pattern, full_text, re.IGNORECASE)
        if match:
            value = match.group(1).strip(" .:-")
            if not re.search(r"(?:MFG|EXP|JAN|FEB|MAR|APR|MAY|JUN|JUL|AUG|SEP|OCT|NOV|DEC)", value, re.I):
                return value

    return None


def extract_date_field(ocr_results, field_type):
    """Extract manufacturing or expiry date from its explicit label."""
    if field_type == "mfg":
        label_pattern = r"(?:mfg|mfd|manufactured|manufacturing(?:\s+date)?)"
    else:
        label_pattern = r"(?:exp|expiry|expires|use\s*before)"

    patterns = [
        rf"{label_pattern}\s*[:.\-]?\s*({DATE_PATTERN})",
        rf"{label_pattern}\s*[:.\-]?\s*([A-Za-z]{{3,9}}\s+\d{{2,4}})",
        rf"{label_pattern}\s*[:.\-]?\s*(\d{{1,2}}[./-]\d{{1,2}}[./-]\d{{2,4}})",
        rf"{label_pattern}\s*[:.\-]?\s*(\d{{1,2}}[./-]\d{{4}})",
    ]

    for _, text, _ in ocr_results:
        text = clean_ocr_text(text)
        for pattern in patterns:
            match = re.search(pattern, text, re.IGNORECASE)
            if match:
                return match.group(1).strip(" .:-")

    full_text = " ".join(clean_ocr_text(text) for _, text, _ in ocr_results)
    for pattern in patterns:
        match = re.search(pattern, full_text, re.IGNORECASE)
        if match:
            return match.group(1).strip(" .:-")

    return None


def extract_product_name(ocr_results):
    """
    Improved product extraction.
    Prioritizes medicine-name lines over ingredient/description lines.
    """

    lines = [
        clean_ocr_text(text)
        for _, text, _ in ocr_results
        if text.strip()
    ]

    # Strong medicine-name indicators
    strong_candidates = []

    for line in lines:
        lower = line.lower()

        if any(keyword in lower for keyword in [
            "paracetamol",
            "acetaminophen",
            "ibuprofen",
            "aspirin",
            "amoxicillin",
            "azithromycin"
        ]):
            strong_candidates.append(line)

    if strong_candidates:
        # Prefer the cleanest line containing the actual medicine name
        return min(
            strong_candidates,
            key=lambda x: (
                len(x),
                x.lower().count("tablet")
            )
        )

    # Second-level candidates
    candidates = []

    for line in lines:
        lower = line.lower()

        if any(keyword in lower for keyword in [
            "tablet",
            "tablets",
            "capsule",
            "capsules",
            "syrup",
            "injection"
        ]):

            # Ignore ingredient-description lines
            if "each uncoated tablet contains" in lower:
                continue

            # Ignore dosage-only lines
            if re.fullmatch(
                r"[\d\s./-]+(?:mg|ml|mcg|g)",
                lower
            ):
                continue

            candidates.append(line)

    if candidates:
        return min(candidates, key=len)

    return None


def run_ocr_best(image_path):
    """Upscale primary + CLAHE fallback. Returns (raw detections, metadata).
    [FIX-3] Returns (None, meta) cleanly if the image can't be read."""
    image_bgr = cv2.imread(str(image_path))
    if image_bgr is None:
        log.warning(f"OCR: could not read image {image_path}")
        return None, {"method": "read_error", "avg_confidence": 0.0, "num_text_regions": 0}

    primary_img = preprocess_upscaled(image_bgr)
    primary_results = reader.readtext(primary_img)
    primary_confs = [c for _, _, c in primary_results]
    primary_conf = float(np.mean(primary_confs)) if primary_confs else 0.0

    use_fallback = (len(primary_results) < 1) or (primary_conf < 0.30)

    if use_fallback:
        fallback_img = preprocess_clahe(image_bgr)
        fallback_results = reader.readtext(fallback_img)
        fallback_confs = [c for _, _, c in fallback_results]
        fallback_conf = float(np.mean(fallback_confs)) if fallback_confs else 0.0

        if fallback_conf > primary_conf:
            return fallback_results, {
                "method": "upscaled_clahe_fallback",
                "avg_confidence": fallback_conf,
                "num_text_regions": len(fallback_results),
            }

    return primary_results, {
        "method": "upscaled_primary",
        "avg_confidence": primary_conf,
        "num_text_regions": len(primary_results),
    }


def medicine_keyword_detected(ocr_results):
    full_text = " ".join(text for _, text, _ in ocr_results)
    return fuzzy_contains(full_text, PRODUCT_KW, threshold=70)


def ocr_evidence_score(ocr_results, avg_confidence):
    if not ocr_results:
        return 0.0, "no_text"
    if not medicine_keyword_detected(ocr_results):
        return 0.25, "generic_text"
    if avg_confidence >= 0.70:
        return 0.80, "high_confidence_medicine_text"
    if avg_confidence >= 0.30:
        return 0.60, "medium_confidence_medicine_text"
    return 0.40, "low_confidence_medicine_text"


def analyze_ocr(image_path):
    ocr_results, meta = run_ocr_best(image_path)
    if not ocr_results:
        return {
            "raw_text": "", "avg_confidence": 0.0, "num_text_regions": 0,
            "method": meta["method"], "product_name": None,
            "batch_number": None, "manufacturing_date": None, "expiry_date": None,
            "evidence_score": 0.0, "evidence_level": "no_text",
        }

    raw_text = " | ".join(text for _, text, _ in ocr_results)
    batch = extract_batch_number(ocr_results)
    mfg = extract_date_field(ocr_results, "mfg")
    exp = extract_date_field(ocr_results, "exp")
    product = extract_product_name(ocr_results)
    score, level = ocr_evidence_score(ocr_results, meta["avg_confidence"])

    return {
        "raw_text": raw_text,
        "avg_confidence": meta["avg_confidence"],
        "num_text_regions": meta["num_text_regions"],
        "method": meta["method"],
        "product_name": product,
        "batch_number": batch,
        "manufacturing_date": mfg,
        "expiry_date": exp,
        "evidence_score": score,
        "evidence_level": level,
    }


