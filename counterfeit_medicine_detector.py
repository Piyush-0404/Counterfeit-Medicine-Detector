MEDICINE_KEYWORDS = [
    "tablet",
    "tablets",
    "capsule",
    "capsules",
    "syrup",
    "injection",
    "medicine",
    "pharma",
    "mg",
    "ml",
    "ip",
    "usp"
]


def detect_medicine_keyword(text):

    text_lower = text.lower()

    return any(
        keyword in text_lower
        for keyword in MEDICINE_KEYWORDS
    )


# ============================================================
# OCR EVIDENCE SCORE
# ============================================================

def calculate_ocr_evidence(
    text,
    confidence,
    num_regions
):

    if num_regions == 0:

        return 0.0, "no_text"

    medicine_detected = (
        detect_medicine_keyword(text)
    )

    if not medicine_detected:

        return 0.25, "generic_text"

    if confidence >= 0.70:

        return 0.80, "high_confidence_medicine_text"

    if confidence >= 0.30:

        return 0.60, "medium_confidence_medicine_text"

    return 0.40, "low_confidence_medicine_text"


