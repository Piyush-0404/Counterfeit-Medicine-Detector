def train_one_epoch(model, dataloader, criterion, optimizer, device):
    model.train()
    running_loss = 0.0

    for batch_idx, (anchors, positives, negatives, _, _) in enumerate(dataloader):
        anchors = anchors.to(device)
        positives = positives.to(device)
        negatives = negatives.to(device)

        # Zero gradients
        optimizer.zero_grad()

        # Forward pass
        anc_emb, pos_emb, neg_emb = model(anchors, positives, negatives)

        # Compute loss
        loss = criterion(anc_emb, pos_emb, neg_emb)

        # Backward pass & optimization step
        loss.backward()
        optimizer.step()

        running_loss += loss.item() * anchors.size(0)

    epoch_loss = running_loss / len(dataloader.dataset)
    return epoch_loss

@torch.no_grad()
def evaluate_embeddings(model, dataloader, device):
    """
    Evaluates the model embeddings on standard validation batches by computing
    mean Euclidean distances of genuine pairs (Anchor-Positive) and counterfeit pairs (Anchor-Negative).
    """
    model.eval()
    genuine_distances = []
    counterfeit_distances = []

    for anchors, positives, negatives, _, _ in dataloader:
        anchors = anchors.to(device)
        positives = positives.to(device)
        negatives = negatives.to(device)

        anc_emb, pos_emb, neg_emb = model(anchors, positives, negatives)

        # Compute Euclidean Distances: sqrt(sum((a - b)^2))
        pos_dist = torch.norm(anc_emb - pos_emb, p=2, dim=1).cpu().numpy()
        neg_dist = torch.norm(anc_emb - neg_emb, p=2, dim=1).cpu().numpy()

        genuine_distances.extend(pos_dist)
        counterfeit_distances.extend(neg_dist)

    mean_genuine = np.mean(genuine_distances)
    mean_counterfeit = np.mean(counterfeit_distances)
    return mean_genuine, mean_counterfeit

