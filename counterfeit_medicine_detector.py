class MedicineTripletDataset(Dataset):
    def __init__(self, metadata_df, real_train_dir, anchor_transform, pos_transform, neg_transform):
        """
        Args:
            metadata_df (pd.DataFrame): DataFrame containing synthetic dataset metadata
            real_train_dir (str): Directory containing genuine training Real images
            anchor_transform: Transform for the Anchor image
            pos_transform: Transform for the Positive image
            neg_transform: Transform for the Negative image
        """
        self.anchor_transform = anchor_transform
        self.pos_transform = pos_transform
        self.neg_transform = neg_transform

        # Retrieve all unique genuine training files
        self.genuine_files = sorted([
            f for f in os.listdir(real_train_dir)
            if os.path.splitext(f)[1].lower() in image_extensions
        ])
        self.real_train_dir = real_train_dir

        # Group synthetic images by their source_image path
        # normalized for directory structure matching
        self.synthetic_mapping = {}
        for _, row in metadata_df.iterrows():
            src_path = os.path.abspath(row['source_image'])
            synth_path = os.path.abspath(row['synthetic_image'])
            if src_path not in self.synthetic_mapping:
                self.synthetic_mapping[src_path] = []
            self.synthetic_mapping[src_path].append(synth_path)

    def __len__(self):
        return len(self.genuine_files)

    def __getitem__(self, idx):
        filename = self.genuine_files[idx]
        anchor_path = os.path.join(self.real_train_dir, filename)
        abs_anchor_path = os.path.abspath(anchor_path)

        # Load Anchor image
        anchor_img = Image.open(anchor_path).convert("RGB")

        # Positive is an independently transformed version of the same genuine image
        pos_img = anchor_img.copy()

        # Negative is chosen randomly from the synthetic variants of this exact source
        neg_variants = self.synthetic_mapping.get(abs_anchor_path, [])
        if not neg_variants:
            raise ValueError(f"No synthetic negatives found for source: {anchor_path}")

        neg_path = random.choice(neg_variants)
        neg_img = Image.open(neg_path).convert("RGB")

        # Apply corresponding transforms
        anchor_tensor = self.anchor_transform(anchor_img)
        pos_tensor = self.pos_transform(pos_img)
        neg_tensor = self.neg_transform(neg_img)

        # We also return paths for verification/visualization purposes
        return anchor_tensor, pos_tensor, neg_tensor, anchor_path, neg_path

