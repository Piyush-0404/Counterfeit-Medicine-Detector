# ============================================================
# OCR SETTINGS
# ============================================================

MIN_TEXT_REGIONS = 1
FALLBACK_CONFIDENCE = 0.30


# ============================================================
# PREPROCESSING
# ============================================================

def preprocess_upscaled(image):
    """
    Primary preprocessing:
    3x upscaling while preserving the original appearance.
    """
    return cv2.resize(
        image,
        None,
        fx=3,
        fy=3,
        interpolation=cv2.INTER_CUBIC
    )


def preprocess_clahe(image):
    """
    Fallback preprocessing:
    3x upscaling + grayscale + CLAHE.
    """
    upscaled = cv2.resize(
        image,
        None,
        fx=3,
        fy=3,
        interpolation=cv2.INTER_CUBIC
    )

    gray = cv2.cvtColor(
        upscaled,
        cv2.COLOR_BGR2GRAY
    )

    clahe = cv2.createCLAHE(
        clipLimit=2.0,
        tileGridSize=(8, 8)
    )

    return clahe.apply(gray)


# ============================================================
# RUN EASY OCR
# ============================================================

def run_ocr(image):

    output = reader.readtext(image)

    texts = []
    confidences = []

    for _, text, confidence in output:

        text = text.strip()

        if text:
            texts.append(text)
            confidences.append(float(confidence))

    full_text = " ".join(texts)

    avg_confidence = (
        sum(confidences) / len(confidences)
        if confidences
        else 0.0
    )

    return {
        "text": full_text,
        "num_regions": len(texts),
        "avg_confidence": avg_confidence
    }


# ============================================================
# COMPLETE OCR PIPELINE
# ============================================================

def process_medicine_image(image_path):

    image = cv2.imread(str(image_path))

    if image is None:
        return {
            "image": image_path.name,
            "ocr_method": "read_error",
            "raw_text": "",
            "num_text_regions": 0,
            "avg_confidence": 0.0,
            "product_name": None,
            "batch_number": None,
            "manufacturing_date": None,
            "expiry_date": None
        }

    # --------------------------------------------------------
    # Primary OCR: Upscaled image
    # --------------------------------------------------------

    primary_image = preprocess_upscaled(image)

    primary_result = run_ocr(primary_image)

    # --------------------------------------------------------
    # Decide whether fallback OCR is necessary
    # --------------------------------------------------------

    use_fallback = (
        primary_result["num_regions"] < MIN_TEXT_REGIONS
        or primary_result["avg_confidence"] < FALLBACK_CONFIDENCE
    )

    if use_fallback:

        fallback_image = preprocess_clahe(image)

        fallback_result = run_ocr(fallback_image)

        # Select the result with better OCR confidence
        if (
            fallback_result["avg_confidence"]
            > primary_result["avg_confidence"]
        ):
            final_result = fallback_result
            ocr_method = "upscaled_clahe_fallback"
        else:
            final_result = primary_result
            ocr_method = "upscaled_primary_after_fallback"

    else:

        final_result = primary_result
        ocr_method = "upscaled_primary"

    # --------------------------------------------------------
    # Extract medicine fields
    # --------------------------------------------------------

    fields = extract_medicine_fields(
        final_result["text"]
    )

    return {
        "image": image_path.name,
        "ocr_method": ocr_method,
        "raw_text": final_result["text"],
        "num_text_regions": final_result["num_regions"],
        "avg_confidence": round(
            final_result["avg_confidence"],
            4
        ),
        "product_name": fields["product_name"],
        "batch_number": fields["batch_number"],
        "manufacturing_date": fields["manufacturing_date"],
        "expiry_date": fields["expiry_date"]
    }


