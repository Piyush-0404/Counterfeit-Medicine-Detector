def extract_batch(text):

    patterns = [

        r"\b(?:batch|b\.?\s*no|lot)\s*[:\-]?\s*([A-Z0-9\-\/]+)",

    ]

    for pattern in patterns:

        match = re.search(
            pattern,
            text,
            re.IGNORECASE
        )

        if match:
            return match.group(1)

    return None


def extract_mfg(text):

    patterns = [

        r"\b(?:mfg|mfd|manufacturing)\s*[:\-]?\s*"
        r"(\d{1,2}[\/\-]\d{2,4})",

    ]

    for pattern in patterns:

        match = re.search(
            pattern,
            text,
            re.IGNORECASE
        )

        if match:
            return match.group(1)

    return None


def extract_expiry(text):

    patterns = [

        r"\b(?:exp|expiry|expires|use before)\s*[:\-]?\s*"
        r"(\d{1,2}[\/\-]\d{2,4})",

    ]

    for pattern in patterns:

        match = re.search(
            pattern,
            text,
            re.IGNORECASE
        )

        if match:
            return match.group(1)

    return None


def extract_product(text):

    lines = [
        x.strip()
        for x in text.split("|")
        if x.strip()
    ]

    medicine_keywords = [
        "tablet",
        "capsule",
        "syrup",
        "injection",
        "mg",
        "ml",
        "medicine",
        "ip"
    ]

    candidates = []

    for line in lines:

        lower = line.lower()

        if any(
            keyword in lower
            for keyword in medicine_keywords
        ):

            cleaned = re.sub(
                r"\b(?:batch|b\.?\s*no|lot).*",
                "",
                line,
                flags=re.IGNORECASE
            )

            cleaned = re.sub(
                r"\b(?:mfg|mfd|manufacturing).*",
                "",
                cleaned,
                flags=re.IGNORECASE
            )

            cleaned = re.sub(
                r"\b(?:exp|expiry|expires|use before).*",
                "",
                cleaned,
                flags=re.IGNORECASE
            )

            cleaned = cleaned.strip(
                " :-|"
            )

            if cleaned:
                candidates.append(
                    cleaned
                )

    if candidates:

        return max(
            candidates,
            key=len
        )

    return None


