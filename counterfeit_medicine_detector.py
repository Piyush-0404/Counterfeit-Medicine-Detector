def prepare_ocr_images(image):

    # Primary: 3x upscale
    upscaled = image.resize(
        (
            image.width * 3,
            image.height * 3
        ),
        Image.Resampling.LANCZOS
    )

    # CLAHE fallback
    gray = np.array(
        upscaled.convert("L")
    )

    clahe = cv2.createCLAHE(
        clipLimit=2.0,
        tileGridSize=(8, 8)
    )

    clahe_img = clahe.apply(
        gray
    )

    return [
        (
            "upscaled_primary",
            np.array(upscaled)
        ),
        (
            "upscaled_clahe_fallback",
            clahe_img
        )
    ]


# ============================================================
# OCR EXTRACTION
# ============================================================

def run_ocr(image):

    candidates = prepare_ocr_images(
        image
    )

    results = []

    for method, img in candidates:

        detections = ocr_reader.readtext(
            img
        )

        text_regions = []

        confidences = []

        for detection in detections:

            if len(detection) >= 3:

                text = str(
                    detection[1]
                ).strip()

                confidence = float(
                    detection[2]
                )

                if text:

                    text_regions.append(
                        text
                    )

                    confidences.append(
                        confidence
                    )

        avg_confidence = (
            np.mean(confidences)
            if confidences
            else 0.0
        )

        results.append({

            "method": method,

            "text_regions":
                text_regions,

            "num_text_regions":
                len(text_regions),

            "avg_confidence":
                float(avg_confidence),

            "raw_text":
                " | ".join(
                    text_regions
                )
        })

    # Select strongest result
    best = max(
        results,
        key=lambda x: (
            x["avg_confidence"],
            x["num_text_regions"]
        )
    )

    return best


