# baseline-vs-classifier comparison later is fair. Smaller distance =
# more "real", so we scan candidate cutoffs from the val distances
# themselves and predict real when distance <= cutoff.
def calibrate_distance_threshold(distances, labels):
    candidates = np.unique(distances)
    best_ba, best_cut = -1, np.median(candidates)
    for cut in candidates:
        preds = (distances <= cut).astype(int)
        tn, fp, fn, tp = confusion_matrix(labels, preds, labels=[0, 1]).ravel()
        rec = recall_score(labels, preds, zero_division=0)
        spec = tn / (tn + fp) if (tn + fp) > 0 else 0
        ba = (rec + spec) / 2
        if ba > best_ba:
            best_ba, best_cut = ba, cut
    return best_cut, best_ba

