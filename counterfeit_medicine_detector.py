def collect_split_embeddings(split_dir):
    """Returns (embeddings, labels, paths). label: 1=Real, 0=Fake.
    [FIX-3] Corrupt/unreadable images are skipped and logged, not fatal.
    """
    embeddings, labels, paths = [], [], []
    n_skipped = 0

    for label_name, label in [("Real", 1), ("Fake", 0)]:
        folder = Path(split_dir) / label_name
        if not folder.exists():
            log.warning(f"Missing folder: {folder}")
            continue
        files = sorted([
            p for p in folder.iterdir()
            if p.suffix.lower() in image_extensions
        ])
        for p in files:
            emb = get_embedding(p)
            if emb is None:
                n_skipped += 1
                continue
            embeddings.append(emb)
            labels.append(label)
            paths.append(str(p))

    if n_skipped:
        log.warning(f"{split_dir}: skipped {n_skipped} unreadable image(s).")

    if not embeddings:
        raise RuntimeError(f"No readable images found under {split_dir}")

    return np.array(embeddings), np.array(labels), paths


