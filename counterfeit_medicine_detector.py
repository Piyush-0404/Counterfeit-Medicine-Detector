def calculate_ocr_evidence(row):

    text = str(row["raw_text"]).strip()
    confidence = float(row["avg_confidence"])

    # No OCR text
    if not text:
        return 0.0

    # Text exists but no recognizable medicine information
    if not row["medicine_keyword_detected"]:
        return 0.25

    # Medicine-related text with low confidence
    if confidence < 0.30:
        return 0.40

    # Medicine-related text with medium confidence
    if confidence < 0.70:
        return 0.60

    # Medicine-related text with high confidence
    return 0.80


ocr_df["ocr_evidence_score"] = (
    ocr_df.apply(
        calculate_ocr_evidence,
        axis=1
    )
)


