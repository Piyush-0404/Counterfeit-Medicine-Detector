DATE_PATTERN = r"""
(
    \b\d{1,2}[/-]\d{1,2}[/-]\d{2,4}\b
    |
    \b\d{1,2}[/-]\d{2,4}\b
    |
    \b\d{1,2}\s*[-/]\s*[A-Za-z]{3,9}\s*[-/]?\s*\d{2,4}\b
    |
    \b[A-Za-z]{3,9}\s*[-/]\s*\d{2,4}\b
)
"""


# ---------------------------------------------------------
# Extract Batch / Lot number
# ---------------------------------------------------------

def extract_batch(text):

    patterns = [
        r"(?:batch\s*(?:no|number)?|b\.?\s*no\.?|lot\s*(?:no|number)?)"
        r"\s*[:#.-]?\s*([A-Z0-9][A-Z0-9./_-]{2,20})",

        r"(?:batch|lot)\s*[:#.-]?\s*([A-Z0-9][A-Z0-9./_-]{2,20})"
    ]

    for pattern in patterns:

        match = re.search(
            pattern,
            text,
            flags=re.IGNORECASE
        )

        if match:
            return match.group(1).strip()

    return None


# ---------------------------------------------------------
# Extract Manufacturing date
# ---------------------------------------------------------

def extract_mfg(text):

    patterns = [
        rf"(?:mfg|mfd|manufactured|manufacturing)"
        rf"\s*(?:date)?\s*[:#.-]?\s*({DATE_PATTERN})"
    ]

    for pattern in patterns:

        match = re.search(
            pattern,
            text,
            flags=re.IGNORECASE | re.VERBOSE
        )

        if match:
            return match.group(1).strip()

    return None


# ---------------------------------------------------------
# Extract Expiry date
# ---------------------------------------------------------

def extract_expiry(text):

    patterns = [
        rf"(?:exp|expiry|expires|use\s*before)"
        rf"\s*(?:date)?\s*[:#.-]?\s*({DATE_PATTERN})"
    ]

    for pattern in patterns:

        match = re.search(
            pattern,
            text,
            flags=re.IGNORECASE | re.VERBOSE
        )

        if match:
            return match.group(1).strip()

    return None


# ---------------------------------------------------------
# Extract likely product name
# ---------------------------------------------------------

def extract_product_name(text):

    # Common medicine-related keywords
    keywords = [
        "tablet",
        "tablets",
        "capsule",
        "capsules",
        "syrup",
        "injection",
        "paracetamol",
        "mg",
        "ml"
    ]

    lines = [
        line.strip()
        for line in re.split(r"[\n|]+", text)
        if line.strip()
    ]

    candidates = []

    for line in lines:

        lower_line = line.lower()

        if any(keyword in lower_line for keyword in keywords):

            # Ignore extremely short OCR fragments
            if len(line) >= 5:
                candidates.append(line)

    if candidates:
        return candidates[0]

    return None


