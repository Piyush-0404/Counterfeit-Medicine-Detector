def analyze_medicine_image(
    image_path
):

    image_path = Path(
        image_path
    )

    image = Image.open(
        image_path
    ).convert("RGB")


    # -------------------------
    # Visual analysis
    # -------------------------

    tensor = inference_transform(
        image
    ).unsqueeze(0).to(device)

    with torch.no_grad():

        embedding = visual_model(
            tensor
        )

    embedding = embedding.squeeze(
        0
    ).cpu()

    visual_distance = torch.norm(
        embedding -
        reference_profile,
        p=2
    ).item()


    # -------------------------
    # OCR
    # -------------------------

    ocr_result = run_ocr(
        image
    )

    raw_text = ocr_result[
        "raw_text"
    ]

    confidence = ocr_result[
        "avg_confidence"
    ]

    num_regions = ocr_result[
        "num_text_regions"
    ]


    # -------------------------
    # Field extraction
    # -------------------------

    product_name = extract_product(
        raw_text
    )

    batch_number = extract_batch(
        raw_text
    )

    manufacturing_date = extract_mfg(
        raw_text
    )

    expiry_date = extract_expiry(
        raw_text
    )


    # -------------------------
    # OCR evidence
    # -------------------------

    ocr_score, ocr_level = (
        calculate_ocr_evidence(
            raw_text,
            confidence,
            num_regions
        )
    )


    # -------------------------
    # Final decision
    # -------------------------

    decision = generate_screening_decision(
        visual_distance,
        ocr_score,
        batch_number,
        manufacturing_date,
        expiry_date
    )


    return {

        "image": image_path.name,

        "visual": {
            "distance": round(
                visual_distance,
                6
            ),

            "threshold":
                VISUAL_THRESHOLD,

            "decision":
                (
                    "visually_consistent"
                    if visual_distance <= VISUAL_THRESHOLD
                    else "visual_mismatch"
                )
        },

        "ocr": {

            "method":
                ocr_result["method"],

            "raw_text":
                raw_text,

            "num_text_regions":
                num_regions,

            "confidence":
                round(
                    confidence,
                    4
                ),

            "product_name":
                product_name,

            "batch_number":
                batch_number,

            "manufacturing_date":
                manufacturing_date,

            "expiry_date":
                expiry_date,

            "evidence_score":
                ocr_score,

            "evidence_level":
                ocr_level
        },

        "screening": decision
    }


