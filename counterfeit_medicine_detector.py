def generate_risk_decision(
    visual_distance,
    ocr_evidence_score,
    ocr_text="",
    product_name=None,
    batch_number=None,
    manufacturing_date=None,
    expiry_date=None
):
    """
    Generate a user-facing screening decision.

    IMPORTANT:
    This is a screening/evidence aggregation layer.
    It is NOT a calibrated probability of counterfeit status.
    """

    red_flags = []
    positive_evidence = []

    # --------------------------------------------------------
    # Visual evidence
    # --------------------------------------------------------

    if visual_distance <= 0.878:

        visual_status = "visually_consistent"

        positive_evidence.append(
            "Visual embedding is within the selected V1 threshold."
        )

    else:

        visual_status = "visual_mismatch"

        red_flags.append(
            "Visual embedding is above the selected V1 threshold."
        )

    # --------------------------------------------------------
    # OCR evidence
    # --------------------------------------------------------

    if ocr_evidence_score >= 0.80:

        ocr_status = "strong_text_evidence"

        positive_evidence.append(
            "High-confidence medicine-related text detected by OCR."
        )

    elif ocr_evidence_score >= 0.60:

        ocr_status = "moderate_text_evidence"

        positive_evidence.append(
            "Medicine-related text detected with moderate OCR confidence."
        )

    elif ocr_evidence_score >= 0.40:

        ocr_status = "weak_text_evidence"

        red_flags.append(
            "Medicine-related OCR text has low confidence."
        )

    elif ocr_evidence_score >= 0.25:

        ocr_status = "generic_text_only"

        red_flags.append(
            "Text was detected, but medicine-specific information "
            "could not be established reliably."
        )

    else:

        ocr_status = "no_text_evidence"

        red_flags.append(
            "No usable OCR text was detected."
        )

    # --------------------------------------------------------
    # Missing metadata
    # --------------------------------------------------------

    if not batch_number:
        red_flags.append(
            "Batch/Lot number could not be reliably extracted."
        )

    if not manufacturing_date:
        red_flags.append(
            "Manufacturing date could not be reliably extracted."
        )

    if not expiry_date:
        red_flags.append(
            "Expiry date could not be reliably extracted."
        )

    # --------------------------------------------------------
    # Decision logic
    # --------------------------------------------------------
    #
    # We intentionally avoid calling something "genuine"
    # because the system is a screening tool.
    # --------------------------------------------------------

    if visual_status == "visual_mismatch":

        risk_level = "HIGH"
        decision = "HIGH RISK / VISUAL MISMATCH"

    elif (
        visual_status == "visually_consistent"
        and ocr_evidence_score >= 0.60
    ):

        risk_level = "LOW"
        decision = "LOW RISK / VISUALLY CONSISTENT"

    else:

        risk_level = "REVIEW"
        decision = "REVIEW REQUIRED"

    return {
        "risk_level": risk_level,
        "decision": decision,
        "visual_distance": round(
            float(visual_distance),
            4
        ),
        "visual_status": visual_status,
        "ocr_evidence_score": round(
            float(ocr_evidence_score),
            4
        ),
        "ocr_status": ocr_status,
        "product_name": product_name,
        "batch_number": batch_number,
        "manufacturing_date": manufacturing_date,
        "expiry_date": expiry_date,
        "positive_evidence": positive_evidence,
        "red_flags": red_flags
    }


print("✅ Final risk-decision function created.")


